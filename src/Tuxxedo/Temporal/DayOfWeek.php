declare(strict_types=1);

namespace Tuxxedo\Temporal;

enum DayOfWeek: int
{
    case MONDAY = 1;
    case TUESDAY = 2;
    case WEDNESDAY = 3;
    case THURSDAY = 4;
    case FRIDAY = 5;
    case SATURDAY = 6;
    case SUNDAY = 7;

    public static function fromInstant(
        InstantInterface $instant,
    ): self {
        return self::from(
            value: (int) $instant->dateTime->format(format: 'N'),
        );
    }
}
